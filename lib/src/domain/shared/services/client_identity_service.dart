/// Интерфейс сервиса для управления идентификатором клиента (реплики).
///
/// Каждая реплика приложения должна иметь стабильный локальный идентификатор,
/// который не зависит от авторизации и сохраняется между перезапусками.
abstract class ClientIdentityService {
  /// Инициализирует сервис (чтение или генерация client_id).
  ///
  /// Должен быть вызван один раз при старте приложения перед использованием
  /// [clientId]. Генерирует новый UUID, если client_id еще не сохранен.
  Future<void> init();

  /// Возвращает идентификатор клиента (UUID) — `source_id` конвертов ulsync.
  ///
  /// **Важно:** [init] должен быть вызван перед использованием этого геттера.
  /// Возвращает тот же UUID, который был сгенерирован при первом запуске.
  ///
  /// **Инвариант установки (SPEC §1.4, третий ранг разрешения конфликтов):**
  /// значение уникально **на эту установку** и не должно попадать на другое
  /// устройство — ни через перенос бэкапа, ни через клон образа эмулятора.
  /// Две установки-тёзки с одним `client_id` создают ничью, которую сверка
  /// не разнимет; это единственный класс расхождений, который круг 1a не лечит.
  /// Генерация одноразовая, значение хранится в настройках установки;
  /// библиотека при подмене отказывает в обмене — приложение не должно
  /// глотать эту ошибку молча.
  String get clientId;
}
